const SLOT_HOURS = ['07:00', '08:00', '10:00', '12:00', '13:00', '14:00', '17:00', '18:00', '21:00', '22:00']

/** Свободные окна аренды: детерминированная сетка, чтобы демо было стабильным. */
export const FREE_SLOTS: FreeSlot[] = COURTS.flatMap((court, courtIndex) =>
  SLOT_HOURS.map((start, slotIndex) => {
    const seed = (courtIndex * 7 + slotIndex * 3) % 5
    if (seed === 0) return null
    return {
      id: `${court.id}-${start}`,
      courtId: court.id,
      dayOffset: slotIndex % 7,
      start,
      durationMin: seed === 4 ? 90 : 60,
      price: court.surface === 'Грунт' ? 2400 : 2000,
    }
  }).filter((slot): slot is FreeSlot => slot !== null),
)

